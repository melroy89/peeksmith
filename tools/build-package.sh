#!/usr/bin/env bash
# Build in a private copy: packaging must not rewrite the working checkout.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
RELEASE_VERSION=$(python3 tools/release-version.py)
OUTPUT="$ROOT/dist"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUTPUT" "$WORK/peeksmith-$RELEASE_VERSION"
# Include uncommitted release preparation during local validation; GitHub builds
# use a clean checkout. Ignored build outputs and .git are excluded.
if [ "$(git rev-parse --show-toplevel 2>/dev/null || true)" = "$ROOT" ]; then
  git ls-files --cached --others --exclude-standard -z |
    tar --null -T - -cf - | tar -xf - -C "$WORK/peeksmith-$RELEASE_VERSION"
else
  # Downloaded source archives have no .git directory.
  tar --exclude='./dist' --exclude='./build' --exclude='./builddir' \
    --exclude='./build_*' --exclude='./obj-*' --exclude='./.git' -cf - . |
    tar -xf - -C "$WORK/peeksmith-$RELEASE_VERSION"
fi
case "${1:-}" in
  deb)
    (cd "$WORK/peeksmith-$RELEASE_VERSION"
     DEB_BUILD_OPTIONS="${DEB_BUILD_OPTIONS:-parallel=4}" dpkg-buildpackage --build=binary --no-sign)
    # Keep distribution-specific assets distinct; dependencies are generated by dh_shlibdeps.
    . /etc/os-release
    ARCH=$(dpkg --print-architecture)
    cp "$WORK/peeksmith_${RELEASE_VERSION}-1_${ARCH}.deb" "$OUTPUT/peeksmith-${RELEASE_VERSION}-${ID}${VERSION_ID}-${ARCH}.deb"
    ;;
  rpm)
    mkdir -p "$WORK/rpm/SOURCES"
    tar -C "$WORK" -czf "$WORK/rpm/SOURCES/peeksmith-$RELEASE_VERSION.tar.gz" "peeksmith-$RELEASE_VERSION"
    rpmbuild -ba --define "_topdir $WORK/rpm" --define '_smp_mflags -j4' "$ROOT/rpm/peeksmith.spec"
    find "$WORK/rpm/RPMS" "$WORK/rpm/SRPMS" -name 'peeksmith-[0-9]*.rpm' -exec cp {} "$OUTPUT/" \;
    ;;
  *) echo 'Usage: tools/build-package.sh deb|rpm' >&2; exit 2 ;;
esac
